function pickFiller(position: "GK" | "DF" | "MF" | "FW", usedNames: Set<string>, offset: number): SquadPlayer {
  const pool = IT_FILLERS[position];
  for (let i = 0; i < pool.length; i += 1) {
    const candidate = pool[(offset + i) % pool.length];
    if (!usedNames.has(candidate.name.toLowerCase())) {
      return candidate;
    }
  }
  return { name: `Primavera ${position} ${offset + 1}`, position };
}

function normalizePlayers(players: SquadPlayer[]): SquadPlayer[] {
  const deduped: SquadPlayer[] = [];
  const usedNames = new Set<string>();

  for (const player of players) {
    const key = player.name.trim().toLowerCase();
    if (!key || usedNames.has(key)) continue;
    usedNames.add(key);
    deduped.push({ ...player });
  }

  let gkCount = deduped.filter((p) => p.position === "GK").length;
  let fillerOffset = 0;

  while (gkCount < 2) {
    const fallback = pickFiller("GK", usedNames, fillerOffset);
    usedNames.add(fallback.name.toLowerCase());
    deduped.unshift(fallback);
    gkCount += 1;
    fillerOffset += 1;
  }

  const fillOrder: Array<"DF" | "MF" | "FW"> = ["DF", "MF", "FW"];
  let fillIndex = 0;
  while (deduped.length < 20) {
    const position = fillOrder[fillIndex % fillOrder.length];
    const fallback = pickFiller(position, usedNames, fillerOffset);
    usedNames.add(fallback.name.toLowerCase());
    deduped.push(fallback);
    fillIndex += 1;
    fillerOffset += 1;
  }

  let trimmed = deduped.slice(0, 20);
  gkCount = trimmed.filter((p) => p.position === "GK").length;
  while (gkCount < 2) {
    let replaceIdx = -1;
    for (let i = trimmed.length - 1; i >= 0; i -= 1) {
      if (trimmed[i].position !== "GK") {
        replaceIdx = i;
        break;
      }
    }
    if (replaceIdx < 0) break;
    const fallback = pickFiller("GK", usedNames, fillerOffset);
    usedNames.add(fallback.name.toLowerCase());
    trimmed[replaceIdx] = fallback;
    gkCount += 1;
    fillerOffset += 1;
  }

  return trimmed;
}

function squad(slug: string, players: SquadPlayer[]): ClubSquadTemplate {
  return { slug, players: normalizePlayers(players) };
}

